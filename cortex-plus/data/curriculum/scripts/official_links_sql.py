"""official-links.json -> additive migration (official_links tablosu + upsert). Kullanım: python3 official_links_sql.py OUT.sql"""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[3]
d = json.load(open(root / "src/lib/curriculum/official-links.json", encoding="utf-8"))
q = lambda s: "'" + s.replace("'", "''") + "'"
rows = ",\n".join(f"  ({q(l['exam'])}, {q(l['title'])}, {q(l['url'])}, {q(l['publisher'])}, {q(d['verifiedAt'])})" for l in d["links"])
sql = f"""-- İlgili resmî kaynaklar (yalnız ekleme). Yalnız dış resmî bağlantı; içerik kopyalanmaz.
-- Kaynak: src/lib/curriculum/official-links.json (her adres {d['verifiedAt']} tarihinde curl ile 200 doğrulandı).
CREATE TABLE IF NOT EXISTS public.official_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exam text NOT NULL,
  title text NOT NULL,
  url text NOT NULL CHECK (url ~ '^https://'),
  publisher text NOT NULL,
  fetched_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (exam, url)
);
ALTER TABLE public.official_links ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.official_links TO anon, authenticated;
GRANT ALL ON public.official_links TO service_role;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'official_links' AND policyname = 'official_links_public_read') THEN
    CREATE POLICY official_links_public_read ON public.official_links FOR SELECT TO anon, authenticated USING (true);
  END IF;
END $$;

INSERT INTO public.official_links (exam, title, url, publisher, fetched_at) VALUES
{rows}
ON CONFLICT (exam, url) DO UPDATE SET title = EXCLUDED.title, publisher = EXCLUDED.publisher, fetched_at = EXCLUDED.fetched_at;
"""
open(sys.argv[1], "w", encoding="utf-8").write(sql)
